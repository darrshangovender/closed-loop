"""Write the Results block of ``README.md`` from ``benchmarks/results.json``.

    python scripts/render_readme_results.py                  print the block
    python scripts/render_readme_results.py --write          replace the block in README.md
    python scripts/render_readme_results.py --check          exit 1 if README.md differs from it
    python scripts/render_readme_results.py --results FILE --readme FILE

The block sits between two marker comments, ``BEGIN`` and ``END`` below, and is a pure function
of the records of ``results.json``: nothing in it is typed by hand and the rest of the README is
not touched. Every number carries its ``k/n`` and what it was measured on where the record has
them. The headline tables are the verdicts with their labels; C-SHIELD with the interlock beside
the shield at equal prominence; C-PLAN under ``nominal`` and ``shifted`` side by side; and
C-PERC, pooled and trend-estimated.

A reader that finds the markers missing gets an error that says so; ``tests/docs/test_readme.py``
skips while the README is a stub.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Final

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from closed_loop.core.results import ResultRecord  # noqa: E402
from closed_loop.eval.claims import Verdict, claim_name, verdicts_from_stored  # noqa: E402
from closed_loop.eval.report import (  # noqa: E402
    QUICK_BANNER,
    SECONDARY_NOTE,
    Index,
    k_over_n,
    num,
    records_from_json,
    split_verdicts,
    table,
    value_ci,
)

BEGIN: Final[str] = "<!-- RESULTS:BEGIN -->"
END: Final[str] = "<!-- RESULTS:END -->"
SOURCE_NOTE: Final[str] = (
    "Generated by `scripts/render_readme_results.py` from `benchmarks/results.json`; "
    "do not edit between the markers."
)
# the three pairs C-SHIELD compares: (pair, shielded arm, unshielded arm, interlock arm)
SHIELD_ROWS: Final[tuple[tuple[str, str, str, str], ...]] = (
    ("H-C", "H-C1", "H-C0", "H-C-I"),
    ("H-G", "H-G1", "H-G0", "H-G-I"),
    ("P", "P1", "P0", "P1-I"),
)


class MarkerError(ValueError):
    """The README does not carry the two marker comments, once each and in order."""


# ----------------------------------------------------------------------------- the block


def render_block(records: Sequence[ResultRecord]) -> str:
    """The Results block, markers included, as text with LF line ends and no trailing blank line."""
    ix = Index(records)
    verdicts = {v.claim: v for v in verdicts_from_stored(records)}
    out: list[str] = [BEGIN, "", f"<!-- {SOURCE_NOTE} -->", ""]
    if ix.param("mode") == "quick":
        out += [f"> **{QUICK_BANNER}.** Development seeds; nothing below is a result.", ""]
    comp = ix.get("run/completeness")
    if comp is not None and comp.value < 1.0:
        out += ["> **INCOMPLETE RUN.** This run does not claim completeness.", ""]
    out += _run_line(ix)
    out += _verdict_table(verdicts)
    out += _shield_section(ix, verdicts)
    out += _plan_section(ix, verdicts)
    out += _perc_section(ix, verdicts)
    out += [END]
    return "\n".join(out).replace("\r\n", "\n")


def _run_line(ix: Index) -> list[str]:
    ix_ = ix
    mode = ix_.param("mode") or "unknown"
    role = ix_.param("seed_role") or "unknown"
    n_seeds = ix_.param("n_seeds") or "unknown"
    variant = ix_.param("primary_variant") or "unknown"
    monitor = ix_.param("monitor_mode") or "unknown"
    return [
        f"Run mode: {mode}. Seed role: {role} ({n_seeds} drawn). Primary perception variant: "
        f"{variant}. Monitor mode chosen on `dev`: {monitor}. All data are SYNTHETIC.",
        "",
    ]


def level_text(v: Verdict) -> str:
    """The level column: C-TOGETHER's label ``completed`` comes from no test (prereg section 7)."""
    return "no test" if v.label == "completed" else f"{v.alpha:.5f}"


def _verdict_table(verdicts: dict[str, Verdict]) -> list[str]:

    out = ["### Verdicts", ""]
    out += [
        "A loss and an inconclusive result are published with the same prominence as a win. "
        "The label of each claim, the level it was judged at, and what the numbers behind it say:",
        "",
    ]
    registered, secondary = split_verdicts(verdicts.values())
    for group in (registered, secondary):
        if group is secondary and group:
            out += [SECONDARY_NOTE, ""]
        if group:
            rows = [(v.claim, v.text, level_text(v), v.headline) for v in group]
            out += table(["Claim", "Verdict", "Level", "What the numbers say"], rows)
    return out


def _measured_on(records: Sequence[ResultRecord | None]) -> list[str]:
    """What the records of a table were measured on, one line each, the arm name folded into
    "each arm in the table" so that nine arms do not give nine near-identical lines."""
    seen: list[str] = []
    for rec in records:
        if rec is None or not rec.measured_on:
            continue
        text = re.sub(
            r"of arm \S+?,", "of each arm in the table with this episode count,", rec.measured_on
        )
        if text not in seen:
            seen.append(text)
    return [f"- Measured on: {text}" for text in seen] + ([""] if seen else [])


def _shield_section(ix: Index, verdicts: dict[str, Verdict]) -> list[str]:
    get = ix.get
    out = ["### C-SHIELD, with the interlock beside it", ""]
    v = verdicts.get("C-SHIELD")
    if v is not None:
        out += [f"Verdict: **{v.text}** (level {v.alpha:.5f}). {v.headline}.", ""]
    rows: list[Sequence[object]] = []
    used: list[ResultRecord | None] = []
    for pair, shielded, unshielded, interlock in SHIELD_ROWS:
        for role, arm in (
            ("shield", shielded),
            ("shield off", unshielded),
            ("interlock", interlock),
        ):
            viol = get(claim_name("C-SHIELD", "viol_p13", arm)) or get(f"{arm}.nominal.m_viol_p13")
            thr, ovr = get(f"{arm}.nominal.throughput"), get(f"{arm}.nominal.override_rate")
            used += [viol, thr, ovr]
            rows.append(
                (pair, arm, role, k_over_n(viol), value_ci(viol),
                 num(thr.value if thr else None), num(ovr.value if ovr else None))
            )  # fmt: skip
    out += table(
        [
            "Pair",
            "Arm",
            "Role",
            "P1-P3 violations (k/n)",
            "Rate (interval)",
            "Throughput",
            "Overrides per 1,000",
        ],
        rows,
    )
    ratio_rows = []
    for pair, shielded, unshielded, interlock in SHIELD_ROWS:
        ratio = get(claim_name("C-SHIELD", "throughput_ratio", pair))
        paired = get(claim_name("C-SHIELD", "interlock", pair))
        used += [ratio, paired]
        ratio_rows.append(
            (pair, f"{shielded} over {unshielded}", num(ratio.value if ratio else None),
             f"{interlock} minus {shielded}", value_ci(paired), paired.n if paired else "-")
        )  # fmt: skip
    out += table(
        [
            "Pair",
            "Throughput ratio",
            "Value",
            "M-VIOL (P1-P3), paired",
            "Difference (interval)",
            "n",
        ],
        ratio_rows,
    )
    if v is not None:
        out += [f"- {note}" for note in v.notes] + [""]
    out += _measured_on(used)
    return out


def _plan_section(ix: Index, verdicts: dict[str, Verdict]) -> list[str]:

    get = ix.get
    primary = ix.param("primary_variant") or "V3"
    out = ["### C-PLAN, nominal and shifted side by side", ""]
    out += [
        "Paired differences, planner minus rule, on the same seeds. The verdict is read on "
        "`nominal`; the `shifted` column decides nothing and is shown with the same prominence.",
        "",
    ]
    rows = []
    used: list[ResultRecord | None] = []
    for planner, reference in (("P0", f"B3-{primary}"), ("P1", "B3-S")):
        for quantity, label in (
            ("cost_diff", "M-COST difference"),
            ("failure_diff", "f_e difference"),
        ):
            nom = get(claim_name("C-PLAN", quantity, planner, "nominal"))
            shi = get(claim_name("C-PLAN", quantity, planner, "shifted"))
            used += [nom, shi]
            rows.append(
                (f"{planner} minus {reference}", label, value_ci(nom), nom.n if nom else "-",
                 value_ci(shi), shi.n if shi else "-")
            )  # fmt: skip
    out += table(
        [
            "Comparison",
            "Quantity",
            "Nominal (interval at the registered level)",
            "n",
            "Shifted (interval at the descriptive level, secondary)",
            "n",
        ],
        rows,
    )
    for claim in ("C-PLAN.P0", "C-PLAN.P0.shifted", "C-PLAN.P1", "C-PLAN.P1.shifted"):
        v = verdicts.get(claim)
        if v is not None:
            standing = "" if split_verdicts([v])[0] else " (secondary row, decides nothing)"
            out.append(f"- {v.claim}{standing}: {v.text}. {v.headline}")
    out.append("")
    out += _measured_on(used)
    return out


def _perc_section(ix: Index, verdicts: dict[str, Verdict]) -> list[str]:

    get = ix.get
    primary = ix.param("primary_variant") or "V3"
    out = ["### C-PERC, pooled and trend-estimated", ""]
    out += [
        "`Gap_B` is the oracle coverage of the open-loop first lives minus that of the closed "
        "loop, paired on the seed. The registered band is plus or minus 0.03.",
        "",
    ]
    rows = []
    used: list[ResultRecord | None] = []
    variants = ["V1"] if primary == "V1" else ["V1", primary]
    for variant in variants:
        pooled = get(claim_name("C-PERC", "gap_b", "pooled", variant))
        trend = get(claim_name("C-PERC", "gap_b", "trend", variant))
        used += [pooled, trend]
        rows.append(
            (variant, value_ci(pooled), pooled.n if pooled else "-", value_ci(trend),
             trend.n if trend else "-")
        )  # fmt: skip
    out += table(["Variant", "Pooled (interval)", "n", "Trend (interval)", "n"], rows)
    for claim in ("C-PERC.pooled", "C-PERC.trend"):
        v = verdicts.get(claim)
        if v is not None:
            out.append(f"- {v.claim}: {v.text}. {v.headline}")
    out.append("")
    out += _measured_on(used)
    return out


# ----------------------------------------------------------------------------- the README


def block_span(text: str) -> tuple[int, int]:
    """Start of the BEGIN marker and the end of the END marker; ``MarkerError`` if not there."""
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise MarkerError(f"the README needs exactly one {BEGIN} and one {END}")
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    if stop <= start:
        raise MarkerError("the END marker comes before the BEGIN marker")
    return start, stop


def current_block(readme: str) -> str:
    start, stop = block_span(readme)
    return readme[start:stop]


def splice(readme: str, block: str) -> str:
    """``readme`` with the text between (and including) the markers replaced by ``block``."""
    start, stop = block_span(readme)
    return readme[:start] + block + readme[stop:]


# ----------------------------------------------------------------------------- command line


def main(argv: Sequence[str] | None = None) -> int:

    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    parser.add_argument("--results", type=Path, default=ROOT / "benchmarks" / "results.json")
    parser.add_argument("--readme", type=Path, default=ROOT / "README.md")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="replace the block in the README")
    mode.add_argument("--check", action="store_true", help="exit 1 if the README block differs")
    args = parser.parse_args(argv)
    records = records_from_json(args.results.read_text(encoding="utf-8"))
    block = render_block(records)
    if not (args.write or args.check):
        sys.stdout.write(block + "\n")
        return 0
    readme = args.readme.read_text(encoding="utf-8").replace("\r\n", "\n")
    try:
        if args.check:
            same = current_block(readme) == block
            print("README Results block: " + ("matches" if same else "DIFFERS from results.json"))
            return 0 if same else 1
        args.readme.write_text(splice(readme, block), encoding="utf-8", newline="\n")
    except MarkerError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(f"wrote the Results block of {args.readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
